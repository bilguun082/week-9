/**
 * Represents the fuel or powertrain type of a vehicle in the dealership inventory.
 */
public enum FuelType {
    /**
     * Traditional petroleum-based internal combustion engine.
     */
    PETROL,

    /**
     * Compression-ignition diesel internal combustion engine.
     */
    DIESEL,

    /**
     * Hybrid powertrain combining an internal combustion engine and electric motor.
     */
    HYBRID
}
